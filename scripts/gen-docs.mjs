function roff(s) {
  return String(s).replace(/\\/g, '\\\\').replace(/^([.'])/gm, '\\&$1').replace(/-/g, '\\-');
}

/** mandoc measures input lines after turning every non-ASCII character into `\[uXXXX]` (8 bytes) */
function roffBytes(s) {
  let n = 0;
  for (const ch of s) n += ch.codePointAt(0) < 0x80 ? 1 : 8;
  return n;
}

/** fill an (already escaped) text line into input lines of ≤ 78 bytes (mandoc STYLE: 80-byte input lines); a wrapped line never starts with a control character */
function fill(text, width = 78) {
  const out = [];
  let cur = '';
  for (const word of String(text).split(' ')) {
    if (cur === '') cur = word;
    else if (roffBytes(`${cur} ${word}`) <= width) cur += ` ${word}`;
    else {
      out.push(cur);
      cur = word;
    }
  }
  if (cur !== '') out.push(cur);
  return out.map((l) => l.replace(/^([.'])/, '\\&$1'));
}

/** a body paragraph: escape then fill */
function body(text) {
  return fill(roff(text));
}

