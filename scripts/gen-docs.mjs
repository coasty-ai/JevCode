#!/usr/bin/env node
// Generates the documentation deliverables of TUI-DESIGN §21 from the registries, so the docs can never
// drift from the code: docs/KEYS.md from KEY_ACTIONS (src/tui/keys/bindings.ts), docs/COMMANDS.md from
// COMMANDS (src/tui/commands/registry.ts), man/jevcode.1 and completions/jevcode.{bash,zsh,fish} from
// cli/args.ts FLAGS + COMMANDS (static scripts; run-id completion is shell-side `ls $JEVCODE_HOME/runs`).
//
//   node scripts/gen-docs.mjs            write every target
//   node scripts/gen-docs.mjs --check    exit 1 and list the targets that are stale (the sync test runs this)
//   node scripts/gen-docs.mjs --print <target>   print one target (keys | commands | man | bash | zsh | fish)
//   node scripts/gen-docs.mjs [--check] --out <dir>   read/write the targets under <dir> instead of the repo root (tests)
//
// The TypeScript registries are loaded through tsx's ESM API (a devDependency), so no build step is needed.
// The man page's .TH date is deterministic so `--check` is stable: SOURCE_DATE_EPOCH (reproducible builds)
// > the commit date of package.json (`git log -1 --format=%cs -- package.json`, the release metadata) > today
// (only when git is unavailable, e.g. an unpacked tarball). Comparisons normalise CRLF so an autocrlf checkout
// never reports every target stale.
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const TARGETS = {
  keys: 'docs/KEYS.md',
  commands: 'docs/COMMANDS.md',
  man: 'man/jevcode.1',
  bash: 'completions/jevcode.bash',
  zsh: 'completions/jevcode.zsh',
  fish: 'completions/jevcode.fish',
};

/** the .TH date (YYYY-MM-DD): SOURCE_DATE_EPOCH > package.json's last commit date > today */
export function manDate(env = process.env) {
  const epoch = env.SOURCE_DATE_EPOCH;
  if (epoch && /^\d+$/.test(epoch)) return new Date(Number(epoch) * 1000).toISOString().slice(0, 10);
  try {
    const out = execFileSync('git', ['log', '-1', '--format=%cs', '--', 'package.json'], { cwd: ROOT, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'], timeout: 10_000 }).trim();
    if (/^\d{4}-\d{2}-\d{2}$/.test(out)) return out;
  } catch {
    // no git: fall through
  }
  return new Date().toISOString().slice(0, 10);
}

/** load the registries (TypeScript) through tsx */
export async function loadRegistries() {
  const { register } = await import('tsx/esm/api');
  const unregister = register();
  try {
    const [bindings, registry, args, defaults] = await Promise.all([
      import(pathToFileURL(join(ROOT, 'src/tui/keys/bindings.ts')).href),
      import(pathToFileURL(join(ROOT, 'src/tui/commands/registry.ts')).href),
      import(pathToFileURL(join(ROOT, 'src/cli/args.ts')).href),
      import(pathToFileURL(join(ROOT, 'src/config/defaults.ts')).href),
    ]);
    const pkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'));
    return {
      KEY_ACTIONS: bindings.KEY_ACTIONS,
      KEY_CONTEXTS: bindings.KEY_CONTEXTS,
      RESERVED_KEYS: bindings.RESERVED_KEYS,
      displayKey: bindings.displayKey,
      COMMANDS: registry.COMMANDS,
      // TUI-DESIGN-3 §1.1 (D-N): the man page derives its mode line from the table and the one constant — no literal names a default
      ENGINE_MODES: registry.ENGINE_MODES,
      DEFAULT_MODE: defaults.DEFAULT_MODE,
      FLAGS: args.FLAGS,
      CLI_COMMANDS: args.COMMANDS,
      version: pkg.version,
      date: manDate(),
    };
  } finally {
    await unregister();
  }
}

const GENERATED_MD = (source) => `<!-- generated by scripts/gen-docs.mjs from ${source}; do not edit by hand — run \`node scripts/gen-docs.mjs\` -->`;

function mdCell(s) {
  return String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
}

function contextTitle(c) {
  return { global: 'Global', composer: 'Composer', review: 'Review box', picker: 'Session picker', palette: 'Palette' }[c] ?? c;
}

