#!/usr/bin/env node
// Regenerate the table of contents at the top of docs/DECISIONS.md.
//
//   node scripts/gen-decisions-toc.mjs            rewrite the block in place
//   node scripts/gen-decisions-toc.mjs --check    exit 1 if the block is stale, print nothing otherwise
//
// The log itself is never touched: the script only replaces the text between the two marker
// comments, and inserts that block just before the first `## ` heading if it is not there yet.
// Running it twice in a row is a no-op, which is what makes it safe to put in a release checklist.
//
// Entries are listed newest first. The log's own order is oldest first and stays that way.
//
// Anchors follow GitHub's rule for Markdown heading ids: lowercase the text, drop everything that
// is not a letter, a digit, a space, an underscore or a hyphen, turn runs of whitespace into single
// hyphens, then disambiguate repeats with `-1`, `-2`, … in document order.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const FILE = join(ROOT, 'docs', 'DECISIONS.md');
const START = '<!-- decisions-toc:start -->';
const END = '<!-- decisions-toc:end -->';
const GENERATED_NOTE = '<!-- Generated by scripts/gen-decisions-toc.mjs. Edit the entries below, not this block. -->';

/** GitHub's heading-anchor slug for one heading's text. */
export function slugOf(text) {
  return text
    .trim()
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\s_-]/gu, '')
    .replace(/\s+/gu, '-');
}

/** The document with any previously generated block removed, so the block never indexes itself. */
export function withoutToc(md) {
  const s = md.indexOf(START);
  const e = md.indexOf(END);
  if (s === -1 || e === -1 || e < s) return md;
  return `${md.slice(0, s)}${md.slice(e + END.length)}`;
}

/** Every `## ` heading of the log, in document order, with a unique anchor each. */
export function headingsOf(md) {
  const seen = new Map();
  const out = [];
  for (const line of withoutToc(md).split('\n')) {
    const m = /^## (.+?)\s*$/.exec(line);
    if (m === null) continue;
    const text = m[1];
    const base = slugOf(text);
    const n = seen.get(base) ?? 0;
    seen.set(base, n + 1);
    out.push({ text, anchor: n === 0 ? base : `${base}-${n}` });
  }
  return out;
}

/** Split `2026-09-19 Some decision` into its date and the rest; the date is optional. */
function splitDate(text) {
  const m = /^(\d{4}-\d{2}-\d{2})\s+(.*)$/.exec(text);
  return m === null ? { date: null, title: text } : { date: m[1], title: m[2] };
}

/** Markdown escaping for link text: only `[`, `]` and a leading `#` can break a list item. */
function escapeLinkText(text) {
  return text.replace(/([[\]])/g, '\\$1');
}

export function renderToc(md) {
  const headings = headingsOf(md);
  const lines = [START, GENERATED_NOTE, '', '## Contents', '', `${headings.length} entries, newest first.`, ''];
  let currentDate = null;
  for (const h of [...headings].reverse()) {
    const { date, title } = splitDate(h.text);
    if (date !== currentDate) {
      if (currentDate !== null) lines.push('');
      lines.push(`**${date ?? 'undated'}**`, '');
      currentDate = date;
    }
    lines.push(`- [${escapeLinkText(title)}](#${h.anchor})`);
  }
  lines.push('', END);
  return lines.join('\n');
}

export function withToc(md) {
  const toc = renderToc(md);
  const s = md.indexOf(START);
  const e = md.indexOf(END);
  if (s !== -1 && e !== -1 && e > s) return `${md.slice(0, s)}${toc}${md.slice(e + END.length)}`;
  const first = md.indexOf('\n## ');
  if (first === -1) return `${md.trimEnd()}\n\n${toc}\n`;
  return `${md.slice(0, first + 1)}${toc}\n\n${md.slice(first + 1)}`;
}

const check = process.argv.includes('--check');
const before = readFileSync(FILE, 'utf8');
const after = withToc(before);
if (before === after) {
  if (!check) console.log(`decisions-toc: ok (${headingsOf(before).length} entries, unchanged)`);
  process.exit(0);
}
if (check) {
  console.error('decisions-toc: docs/DECISIONS.md is stale; run `node scripts/gen-decisions-toc.mjs`');
  process.exit(1);
}
writeFileSync(FILE, after);
console.log(`decisions-toc: rewrote the contents block (${headingsOf(after).length} entries)`);
